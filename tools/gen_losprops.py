#!/usr/bin/env python3
"""Generate smali-stubs/LosProps.smali: system properties the OnePlus camera expects, answered
inside the camera's own process instead of being set system-wide.

Every read of android.os.SystemProperties in oplus-camera-stubs.jar (which also backs
com.oplus.wrapper.os.SystemProperties, OplusSystemProperties and OplusBuild) and the app's two
reflective reads go through com.oplus.camera.los.LosProps: keys listed in PROPS get the value
below, any other key falls through to the real system property. Edit PROPS, then rerun:
    python3 tools/gen_losprops.py
"""

from pathlib import Path

# Values from ColorOS CPH2745_17.0.1.201(EX01) (11.C.80); persist.camera.override_* are not in its props.
PROPS = {
    'ro.build.version.oplus.api': '40',
    'ro.build.version.oplus.sub_api': '25',
    'ro.build.version.oplusrom': 'V17.0.0',
    'ro.oplus.system.camera.name': 'com.oplus.camera',
    'ro.oplus.camera.defercap.support': '1',  # required: the app throws without it
    'ro.oplus.camera.defercap.all.quick.visible.support': '1',
    'persist.camera.override_enable': 'true',
    'persist.camera.override_preview_hdr_support': 'false',
    'persist.sys.feature.localhdr_version': '2',
    'persist.sys.feature.uhdr.support': 'true',
    'persist.sys.oplus.anim_level': '1',
}

SP = 'Landroid/os/SystemProperties;'
S = 'Ljava/lang/String;'


def value_method():
    out = [
        '.method private static value(Ljava/lang/String;)Ljava/lang/String;',
        '    .registers 3',
        '',
        '    if-nez p0, :start',
        '    const/4 v0, 0x0',
        '    return-object v0',
        '',
        '    :start',
    ]
    for i, (k, v) in enumerate(PROPS.items()):
        out += [
            f'    const-string v0, "{k}"',
            '    invoke-virtual {v0, p0}, Ljava/lang/String;->equals(Ljava/lang/Object;)Z',
            '    move-result v1',
            f'    if-eqz v1, :n{i}',
            f'    const-string v0, "{v}"',
            '    return-object v0',
            f'    :n{i}',
        ]
    out += ['    const/4 v0, 0x0', '    return-object v0', '.end method', '']
    return out


BODY = f'''.class public final Lcom/oplus/camera/los/LosProps;
.super Ljava/lang/Object;
.source "LosProps.java"


# Generated by tools/gen_losprops.py. Do not edit by hand.

.method private constructor <init>()V
    .registers 1
    invoke-direct {{p0}}, Ljava/lang/Object;-><init>()V
    return-void
.end method

@VALUE@
.method public static get(Ljava/lang/String;)Ljava/lang/String;
    .registers 2
    invoke-static {{p0}}, Lcom/oplus/camera/los/LosProps;->value({S}){S}
    move-result-object v0
    if-eqz v0, :real
    return-object v0
    :real
    invoke-static {{p0}}, {SP}->get({S}){S}
    move-result-object v0
    return-object v0
.end method

.method public static get(Ljava/lang/String;Ljava/lang/String;)Ljava/lang/String;
    .registers 3
    invoke-static {{p0}}, Lcom/oplus/camera/los/LosProps;->value({S}){S}
    move-result-object v0
    if-eqz v0, :real
    return-object v0
    :real
    invoke-static {{p0, p1}}, {SP}->get({S}{S}){S}
    move-result-object v0
    return-object v0
.end method

# getInt/getLong: a value that isn't a number gives the default, as in SystemProperties
.method public static getInt(Ljava/lang/String;I)I
    .registers 3
    invoke-static {{p0}}, Lcom/oplus/camera/los/LosProps;->value({S}){S}
    move-result-object v0
    if-eqz v0, :real
    :try_start_0
    invoke-static {{v0}}, Ljava/lang/Integer;->parseInt({S})I
    move-result v0
    :try_end_0
    .catch Ljava/lang/NumberFormatException; {{:try_start_0 .. :try_end_0}} :bad
    return v0
    :bad
    return p1
    :real
    invoke-static {{p0, p1}}, {SP}->getInt({S}I)I
    move-result v0
    return v0
.end method

.method public static getLong(Ljava/lang/String;J)J
    .registers 5
    invoke-static {{p0}}, Lcom/oplus/camera/los/LosProps;->value({S}){S}
    move-result-object v0
    if-eqz v0, :real
    :try_start_0
    invoke-static {{v0}}, Ljava/lang/Long;->parseLong({S})J
    move-result-wide v0
    :try_end_0
    .catch Ljava/lang/NumberFormatException; {{:try_start_0 .. :try_end_0}} :bad
    return-wide v0
    :bad
    return-wide p1
    :real
    invoke-static {{p0, p1, p2}}, {SP}->getLong({S}J)J
    move-result-wide v0
    return-wide v0
.end method

.method public static getBoolean(Ljava/lang/String;Z)Z
    .registers 4
    invoke-static {{p0}}, Lcom/oplus/camera/los/LosProps;->value({S}){S}
    move-result-object v0
    if-eqz v0, :real
    const-string v1, "true"
    invoke-virtual {{v1, v0}}, Ljava/lang/String;->equals(Ljava/lang/Object;)Z
    move-result v1
    if-nez v1, :yes
    const-string v1, "1"
    invoke-virtual {{v1, v0}}, Ljava/lang/String;->equals(Ljava/lang/Object;)Z
    move-result v1
    if-nez v1, :yes
    const-string v1, "false"
    invoke-virtual {{v1, v0}}, Ljava/lang/String;->equals(Ljava/lang/Object;)Z
    move-result v1
    if-nez v1, :no
    const-string v1, "0"
    invoke-virtual {{v1, v0}}, Ljava/lang/String;->equals(Ljava/lang/Object;)Z
    move-result v1
    if-nez v1, :no
    return p1
    :yes
    const/4 v0, 0x1
    return v0
    :no
    const/4 v0, 0x0
    return v0
    :real
    invoke-static {{p0, p1}}, {SP}->getBoolean({S}Z)Z
    move-result v0
    return v0
.end method
'''

if __name__ == '__main__':
    out = Path(__file__).parent / 'smali-stubs' / 'LosProps.smali'
    out.write_text(BODY.replace('@VALUE@', '\n'.join(value_method())), newline='\n')
    print(out)
